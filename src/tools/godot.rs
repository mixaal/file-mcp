/// Godot project scaffolding — 3D (FPS) and 2D (platformer).
use std::path::PathBuf;
use tokio::fs;

pub async fn scaffold_3d(dir: &PathBuf, name: &str) -> Result<(), String> {
    // ── directory skeleton ────────────────────────────────────────────────────
    for sub in &[
        "assets/models",
        "assets/textures",
        "assets/materials",
        "assets/sounds",
        "assets/fonts",
        "scenes",
        "scripts",
    ] {
        fs::create_dir_all(dir.join(sub))
            .await
            .map_err(|e| e.to_string())?;
    }

    // ── project files ─────────────────────────────────────────────────────────
    write(dir, "project.godot", &project_godot_3d(name)).await?;
    write(dir, "scripts/player.gd", PLAYER_GD_3D).await?;
    write(dir, "scripts/game_manager.gd", GAME_MANAGER_GD).await?;
    write(dir, "scenes/main.tscn", MAIN_TSCN_3D).await?;

    Ok(())
}

pub async fn scaffold_2d(dir: &PathBuf, name: &str) -> Result<(), String> {
    for sub in &[
        "assets/sprites",
        "assets/textures",
        "assets/sounds",
        "assets/fonts",
        "scenes",
        "scripts",
    ] {
        fs::create_dir_all(dir.join(sub))
            .await
            .map_err(|e| e.to_string())?;
    }

    write(dir, "project.godot", &project_godot_2d(name)).await?;
    write(dir, "scripts/player.gd", PLAYER_GD_2D).await?;
    write(dir, "scripts/game_manager.gd", GAME_MANAGER_GD).await?;
    write(dir, "scenes/main.tscn", MAIN_TSCN_2D).await?;

    Ok(())
}

async fn write(dir: &PathBuf, rel: &str, content: &str) -> Result<(), String> {
    fs::write(dir.join(rel), content)
        .await
        .map_err(|e| format!("write {rel}: {e}"))
}


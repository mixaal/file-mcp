// ── scripts/player.gd (3D FPS) ───────────────────────────────────────────────

const PLAYER_GD_3D: &str = r#"extends CharacterBody3D

const SPEED           := 5.0
const JUMP_VELOCITY   := 4.5
const MOUSE_SENSITIVITY := 0.003
const MAX_LOOK_ANGLE  := 80.0   # degrees, clamped to avoid gimbal flip

@onready var _camera: Camera3D = $Camera3D

func _ready() -> void:
    Input.set_mouse_mode(Input.MOUSE_MODE_CAPTURED)

func _unhandled_input(event: InputEvent) -> void:
    if event is InputEventMouseMotion and \
            Input.get_mouse_mode() == Input.MOUSE_MODE_CAPTURED:
        # Horizontal look — rotate the whole body.
        rotate_y(-event.relative.x * MOUSE_SENSITIVITY)
        # Vertical look — tilt the camera only.
        _camera.rotate_x(-event.relative.y * MOUSE_SENSITIVITY)
        _camera.rotation.x = clamp(
            _camera.rotation.x,
            -deg_to_rad(MAX_LOOK_ANGLE),
             deg_to_rad(MAX_LOOK_ANGLE)
        )

func _physics_process(delta: float) -> void:
    # Gravity
    if not is_on_floor():
        velocity += get_gravity() * delta

    # Jump
    if Input.is_action_just_pressed("jump") and is_on_floor():
        velocity.y = JUMP_VELOCITY

    # Horizontal movement in the direction the camera faces.
    var input_dir := Input.get_vector(
        "move_left", "move_right", "move_forward", "move_back"
    )
    var direction := (
        transform.basis * Vector3(input_dir.x, 0, input_dir.y)
    ).normalized()

    if direction:
        velocity.x = direction.x * SPEED
        velocity.z = direction.z * SPEED
    else:
        velocity.x = move_toward(velocity.x, 0, SPEED)
        velocity.z = move_toward(velocity.z, 0, SPEED)

    move_and_slide()
"#;

// ── scripts/player.gd (2D platformer) ────────────────────────────────────────

const PLAYER_GD_2D: &str = r#"extends CharacterBody2D

const SPEED         := 200.0
const JUMP_VELOCITY := -420.0
const GRAVITY       := 980.0    # pixels/s², overrides project gravity if set

func _physics_process(delta: float) -> void:
    # Gravity
    if not is_on_floor():
        velocity.y += GRAVITY * delta

    # Jump
    if Input.is_action_just_pressed("jump") and is_on_floor():
        velocity.y = JUMP_VELOCITY

    # Horizontal movement
    var dir := Input.get_axis("move_left", "move_right")
    if dir != 0:
        velocity.x = dir * SPEED
    else:
        velocity.x = move_toward(velocity.x, 0, SPEED)

    move_and_slide()
"#;

